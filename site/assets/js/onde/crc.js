// Polpo Onde — codici di controllo.

/** CRC-8 (polinomio 0x07, valore iniziale 0x00). Per «123456789» vale 0xF4. */
export function crc8(bytes) {
  let crc = 0;
  for (const b of bytes) {
    crc ^= b;
    for (let i = 0; i < 8; i++) crc = crc & 0x80 ? ((crc << 1) ^ 0x07) & 0xff : (crc << 1) & 0xff;
  }
  return crc;
}

/** CRC-16/CCITT-FALSE (polinomio 0x1021, valore iniziale 0xFFFF). Per «123456789» vale 0x29B1. */
export function crc16(bytes) {
  let crc = 0xffff;
  for (const b of bytes) {
    crc ^= b << 8;
    for (let i = 0; i < 8; i++) crc = crc & 0x8000 ? ((crc << 1) ^ 0x1021) & 0xffff : (crc << 1) & 0xffff;
  }
  return crc;
}
